const ALIASES = {
  arrow: 'chevron',
  flame: 'fire',
};

export function icon(name = 'dot', size = 16, className = '') {
  const rows = ICONS[ALIASES[name] || name] || ICONS.dot;
  const cells = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < 8; x += 1) {
      if (row[x] === '1') cells.push(`<rect x="${x}" y="${y}" width="1" height="1"/>`);
    }
  });
  return `<svg class="px-icon ${className}" width="${size}" height="${size}" viewBox="0 0 8 8" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${cells.join('')}</svg>`;
}

export function hasIcon(name) {
  return Boolean(ICONS[name]);
}

